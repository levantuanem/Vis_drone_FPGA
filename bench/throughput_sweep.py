    ap.add_argument("--batches", default="1,100")           # PAPER FACT Table 9
    ap.add_argument("--reps", type=int, default=10)         # A32
    ap.add_argument("--json", default="results/throughput_sweep.json")
    ap.add_argument("--show-reference", action="store_true",
                    help="print the paper's Table 9 and the repo's stale "
                         "measurement; needs no hardware")
    args = ap.parse_args(argv)

    if args.show_reference:
        print("PAPER FACT Table 9 (CONTEXT, not targets):")
        print("  {:>5} {:>6} {:>12} {:>10}".format("MHz", "batch", "runtime_ms", "FPS"))
        for r in PAPER_TABLE9:
            print("  {:>5} {:>6} {:>12.3f} {:>10.3f}".format(
                r["clock"], r["batch"], r["runtime_ms"], r["fps"]))
        print("\nREPOSITORY FACT nw_metrics.txt (spec P12 -- does NOT corroborate):")
        print("  {}".format(json.dumps(REPO_STALE_MEASUREMENT)))
        print("\nThroughput definition (REPOSITORY FACT driver_base.py:421):")
