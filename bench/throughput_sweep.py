def mean_sd(xs):
    n = len(xs)
    if n == 0:
        return None, None
    m = sum(xs) / float(n)
    if n < 2:
        return m, 0.0
    var = sum((x - m) ** 2 for x in xs) / float(n - 1)
    return m, math.sqrt(var)


def run(bitfile, clocks, batches, reps, out_json=None, driver_dir="."):
    sys.path.insert(0, driver_dir)
    from driver_base import FINNExampleOverlay      # generated by T1.9 (3.10.2)
    from driver import io_shape_dict                # generated by T1.9

    rows = []
    for clk in clocks:
        for bs in batches:
            accel = FINNExampleOverlay(
                bitfile_name=bitfile, platform="zynq-iodma",
                io_shape_dict=io_shape_dict, batch_size=bs, fclk_mhz=float(clk))
            fps_runs, rt_runs, din, dout = [], [], [], []
            for _ in range(reps):
                # REPOSITORY FACT semantics: buffers already in DRAM; this call
                # times execute_on_buffers() only.
                res = accel.throughput_test()
                fps_runs.append(res["throughput[images/s]"])
                rt_runs.append(res["runtime[ms]"])
                din.append(res.get("DRAM_in_bandwidth[MB/s]", 0.0))
                dout.append(res.get("DRAM_out_bandwidth[MB/s]", 0.0))
            f_m, f_s = mean_sd(fps_runs)
            r_m, r_s = mean_sd(rt_runs)
            rows.append({
                "clock_mhz": clk, "batch": bs, "reps": reps,
                "fps_mean": f_m, "fps_sd": f_s,
                "runtime_ms_mean": r_m, "runtime_ms_sd": r_s,
                "dram_in_mbps_mean": mean_sd(din)[0],
                "dram_out_mbps_mean": mean_sd(dout)[0],
                "all_fps": fps_runs,
            })
            print("{:>4} MHz  batch {:>3}  {:8.3f} +/- {:5.3f} FPS  "
                  "({:9.3f} +/- {:6.3f} ms)".format(clk, bs, f_m, f_s, r_m, r_s))

    doc = {
        "_provenance": {
            "definition": "REPOSITORY FACT driver_base.py:421 -- execute_on_buffers "
                          "only; fold/pack/copy EXCLUDED",
            "sweep": "PAPER FACT 4.2.6 -- clocks 50/100/200, batch 1/100",
            "repetitions": "A32 / I2 -- mean +/- sd, an improvement on the paper",
            "corroboration": "spec P12 -- Table 9 is single-source; the repo's "
                             "only committed measurement disagrees 4.4x",
        },
        "bitfile": bitfile, "rows": rows,
        "paper_table9_for_context": PAPER_TABLE9,
        "repository_stale_measurement": REPO_STALE_MEASUREMENT,
    }
    if out_json:
        with open(out_json, "w") as fh:
            json.dump(doc, fh, indent=2)
    return doc


