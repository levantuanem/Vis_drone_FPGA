from streamer import protocol as P      # noqa: E402
from streamer import fnn_package        # noqa: E402

OUT_DTYPE_CODE = P.DTYPE_INT8          # REPOSITORY FACT odt == INT8


class AcceleratorHandle(object):
    """Thin wrapper over the FINN-generated PYNQ overlay.

    Kept separate so the server logic is testable with a stub in place of PYNQ.
    """

    def __init__(self):
        self.driver = None
        self.shape_dict = None
        self.md5 = None
        self.info = None

    def load(self, extracted):
        from driver_base import FINNExampleOverlay   # generated by step 04 (3.10.2)
        with open(extracted["shape_dict_path"], "rb") as fh:
            self.shape_dict = pickle.load(fh)
        self.info = extracted["info"]
        self.md5 = extracted["md5"]
        self.driver = FINNExampleOverlay(
            bitfile_name=os.path.join(extracted["dir"], "model.bit"),
            platform="zynq-iodma",
            io_shape_dict=self.shape_dict,
            batch_size=1,
            fclk_mhz=float(self.info["max_clock_freq"]),   # REPOSITORY FACT 200.0
        )
        return self

    def infer_batch(self, arrays):
        import numpy as np
        self.driver.batch_size = len(arrays)
        batch = np.stack(arrays, axis=0)
        return self.driver.execute(batch)

    @property
    def loaded(self):
        return self.driver is not None


class InferServer(object):
    def __init__(self, host="0.0.0.0", port=P.DEFAULT_PORT,
                 accel=None, batch_cap=P.SERVER_BATCH_CAP, workdir=None):
        self.host = host
        self.port = int(port)
        self.accel = accel or AcceleratorHandle()
        self.batch_cap = int(batch_cap)
        self.workdir = workdir or tempfile.mkdtemp(prefix="finn_streamer_")
        self.inference_queue = None
        self.result_sinks = {}
        self.clients = set()
        self._worker = None
        self._stop = threading.Event()

    # -- control ----------------------------------------------------------

    def status(self):
        return {
            "status": P.STATUS_INIT_DONE if self.accel.loaded else P.STATUS_UNINIT,
            "model_hash": self.accel.md5,
            "model_info": self.accel.info,
            "queue_size": self.inference_queue.qsize() if self.inference_queue else 0,
            "active_clients": len(self.clients),
            "batch_cap": self.batch_cap,
        }

    def load_model(self, b64_blob, expected_md5=None):
        """PAPER FACT 3.11.13 -- extract, verify, parse, configure, start worker."""
        path = os.path.join(self.workdir, "incoming.fnn")
        with open(path, "wb") as fh:
            fh.write(base64.b64decode(b64_blob))
        digest = fnn_package.md5_of_file(path)
        if expected_md5 and digest != expected_md5:
            raise fnn_package.PackageError(
                "MD5 mismatch: client {} vs received {}".format(expected_md5, digest))
        if self.accel.md5 == digest:
            return {"status": "already_loaded", "model_hash": digest}
        extracted = fnn_package.extract(path, os.path.join(self.workdir, "model"))
        self.accel.load(extracted)
        self.inference_queue = queue.Queue()
        self._stop.clear()
        self._worker = threading.Thread(target=self._worker_loop, daemon=True)
        self._worker.start()
        return {"status": "loaded", "model_hash": digest,
                "model_info": extracted["info"]}

    # -- inference worker --------------------------------------------------

    def _worker_loop(self):
        """PAPER FACT 3.11.9 -- aggregate up to `batch_cap` frames per call."""
        import numpy as np
        while not self._stop.is_set():
            try:
                first = self.inference_queue.get(timeout=0.1)
            except queue.Empty:
                continue
            batch = [first]
            while len(batch) < self.batch_cap:
                try:
                    batch.append(self.inference_queue.get_nowait())
                except queue.Empty:
                    break
            arrays = [b["array"] for b in batch]
            t0 = time.time()
            try:
                out = self.accel.infer_batch(arrays)
            except Exception as exc:                      # pragma: no cover
                for b in batch:
                    b["on_error"](str(exc))
                continue
            dt = time.time() - t0
            out = np.asarray(out)
            for i, b in enumerate(batch):
                b["on_result"](out[i], dt / len(batch))
            for _ in batch:
                self.inference_queue.task_done()

    def submit(self, frame_id, array, on_result, on_error=None):
        if not self.accel.loaded or self.inference_queue is None:
            raise RuntimeError("no model loaded (status={})".format(P.STATUS_UNINIT))
        self.inference_queue.put({
            "frame_id": frame_id, "array": array, "on_result": on_result,
            "on_error": on_error or (lambda msg: None)})

    def shutdown(self):
        self._stop.set()
        if self._worker:
            self._worker.join(timeout=2.0)

    # -- websocket plumbing ------------------------------------------------

    async def _handle(self, websocket, path=None):     # pragma: no cover (needs ws)
        self.clients.add(websocket)
        loop = asyncio.get_event_loop()
        try:
            async for message in websocket:
                if isinstance(message, (bytes, bytearray)):
                    hdr, payload = P.decode_frame(message)
                    arr = P.payload_to_array(hdr, payload)

                    def on_result(out, latency, fid=hdr["frame_id"]):
                        msg = P.encode_frame(fid, out, OUT_DTYPE_CODE)
                        asyncio.run_coroutine_threadsafe(websocket.send(msg), loop)

                    self.submit(hdr["frame_id"], arr, on_result)
                    await websocket.send(json.dumps(
                        {"frame_id": hdr["frame_id"], "status": "queued"}))
                else:
                    req = json.loads(message)
                    cmd = req.get("cmd") or req.get("command")
                    if cmd == P.CMD_STATUS:
                        await websocket.send(json.dumps(self.status()))
                    elif cmd == P.CMD_LOAD_MODEL:
                        res = self.load_model(req["payload"], req.get("md5"))
                        await websocket.send(json.dumps(res))
                    else:
                        await websocket.send(json.dumps(
                            {"error": "unknown command {!r}".format(cmd)}))
        finally:
            self.clients.discard(websocket)

    def serve_forever(self):                            # pragma: no cover
        import websockets
        async def _main():
            async with websockets.serve(self._handle, self.host, self.port,
                                        max_size=None):
                print("InferServer listening on ws://{}:{}".format(
                    self.host, self.port))
                await asyncio.Future()
        asyncio.run(_main())


